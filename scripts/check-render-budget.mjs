import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/portfolio/renderBudget.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module,exports:module.exports});
const budget=new module.exports.RenderBudget();
assert.equal(budget.sample(35),false);assert.equal(budget.scale,1);
assert.equal(budget.sample(35),true);assert.equal(budget.scale,0.9);
for(let i=0;i<30;i++)budget.sample(25);
assert.equal(budget.scale,0.7);
for(let i=0;i<3;i++)assert.equal(budget.sample(60),false);
assert.equal(budget.sample(60),true);assert.equal(budget.scale,0.8);
for(let i=0;i<30;i++)budget.sample(60);
assert.equal(budget.scale,1);
for(let i=0;i<20;i++)budget.sample(i%2?60:40);
assert.equal(budget.scale,1);
budget.reset();assert.equal(budget.scale,1);
